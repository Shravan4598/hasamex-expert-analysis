    @field_validator("quote", "source_text")
    @classmethod
    def normalize_evidence_text(cls, value: str) -> str:
        """Normalize surrounding whitespace while preserving wording."""

        normalized = " ".join(value.split())

        if not normalized:
            raise ValueError("Evidence text cannot be empty.")

        return normalized


