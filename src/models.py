"""
Core domain models for the Hasamex Expert Analysis application.

These models define the structured contracts shared by the ingestion,
retrieval, evidence, and analysis layers.

The application deliberately keeps source metadata attached to every
piece of evidence so that generated answers can be traced back to the
original transcript.
"""

from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator


class SpeakerType(str, Enum):
    """Supported transcript speaker types."""

    INTERVIEWER = "interviewer"
    EXPERT = "expert"
    UNKNOWN = "unknown"


class EvidenceStatus(str, Enum):
    """Status of evidence validation."""

    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    REJECTED = "rejected"


class DifferenceType(str, Enum):
    """Classification used when comparing expert viewpoints."""

    DIRECT_DISAGREEMENT = "direct_disagreement"
    DIFFERENT_EMPHASIS = "different_emphasis"
    DIFFERENT_EXPERIENCE = "different_experience"
    COMPLEMENTARY = "complementary"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


