class TranscriptSegment(BaseModel):
    """
    A timestamped speaker segment from an original transcript.

    The parser creates these objects directly from source transcript
    content. Timestamps therefore originate from the source and are
    never generated by the LLM.
    """

    model_config = ConfigDict(extra="forbid")

    segment_id: str = Field(
        ...,
        min_length=1,
        description="Stable identifier for this transcript segment.",
    )

    document_id: str = Field(
        ...,
        min_length=1,
        description="Identifier of the parent transcript.",
    )

    source_file: str = Field(
        ...,
        min_length=1,
        description="Original transcript filename.",
    )

    expert_name: str = Field(
        ...,
        min_length=1,
        description="Expert associated with the transcript.",
    )

    expert_role: str = Field(
        ...,
        min_length=1,
        description="Role of the expert.",
    )

    market: str = Field(
        ...,
        min_length=1,
        description="Market represented by the expert.",
    )

    speaker: str = Field(
        ...,
        min_length=1,
        description="Original speaker label from the transcript.",
    )

    speaker_type: SpeakerType = Field(
        default=SpeakerType.UNKNOWN,
        description="Normalized speaker category.",
    )

    text: str = Field(
        ...,
        min_length=1,
        description="Original transcript text for this segment.",
    )

    start_timestamp: str = Field(
        ...,
        min_length=1,
        description="Source timestamp marking the start of the segment.",
    )

    end_timestamp: str | None = Field(
        default=None,
        description=(
            "Timestamp marking the end of the segment when it can be "
            "determined from the source."
        ),
    )

    start_seconds: int = Field(
        ...,
        ge=0,
        description="Start timestamp converted to seconds.",
    )

    end_seconds: int | None = Field(
        default=None,
        ge=0,
        description="End timestamp converted to seconds when available.",
    )

    @field_validator("text")
    @classmethod
    def normalize_text(cls, value: str) -> str:
        """Remove accidental surrounding whitespace from transcript text."""

        normalized = " ".join(value.split())

        if not normalized:
            raise ValueError("Transcript segment text cannot be empty.")

        return normalized

    @field_validator("end_seconds")
    @classmethod
    def validate_end_seconds(
        cls,
        value: int | None,
        info,
    ) -> int | None:
        """Ensure an explicit end timestamp is not before its start."""

        if value is None:
            return value

        start_seconds = info.data.get("start_seconds")

        if start_seconds is not None and value < start_seconds:
            raise ValueError(
                "end_seconds cannot be earlier than start_seconds."
            )

        return value


class TranscriptChunk(BaseModel):
    """
    A retrieval-ready chunk built from one or more transcript segments.

    Source metadata is intentionally duplicated onto the chunk so it is
    available directly from vector-store metadata after retrieval.
    """

    model_config = ConfigDict(extra="forbid")

    chunk_id: str = Field(
        ...,
        min_length=1,
        description="Stable identifier for the retrieval chunk.",
    )

    document_id: str = Field(
        ...,
        min_length=1,
        description="Identifier of the parent transcript.",
    )

    source_file: str = Field(
        ...,
        min_length=1,
        description="Original transcript filename.",
    )

    expert_name: str = Field(
        ...,
        min_length=1,
        description="Expert associated with the chunk.",
    )

    expert_role: str = Field(
        ...,
        min_length=1,
        description="Role of the expert.",
    )

    market: str = Field(
        ...,
        min_length=1,
        description="Market represented by the expert.",
    )

    speaker: str = Field(
        ...,
        min_length=1,
        description="Primary speaker represented in the chunk.",
    )

    speaker_type: SpeakerType = Field(
        default=SpeakerType.UNKNOWN,
        description="Normalized speaker category.",
    )

    text: str = Field(
        ...,
        min_length=1,
        description="Text indexed for retrieval.",
    )

    segment_ids: list[str] = Field(
        default_factory=list,
        description="Source segments represented in this chunk.",
    )

    start_timestamp: str = Field(
        ...,
        min_length=1,
        description="Timestamp of the first source segment.",
    )

    end_timestamp: str | None = Field(
        default=None,
        description="Timestamp of the final source segment when available.",
    )

    start_seconds: int = Field(
        ...,
        ge=0,
        description="Start timestamp in seconds.",
    )

    end_seconds: int | None = Field(
        default=None,
        ge=0,
        description="End timestamp in seconds when available.",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional retrieval metadata.",
    )

    @field_validator("text")
    @classmethod
    def normalize_text(cls, value: str) -> str:
        """Normalize whitespace without changing source wording."""

        normalized = " ".join(value.split())

        if not normalized:
            raise ValueError("Chunk text cannot be empty.")

        return normalized


